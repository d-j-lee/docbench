const DICTS: Record<string, Dict> = { ko, en };
/** 시험용: 두 말의 낱말이 같은지 */
export const dictKeys = (): Record<string, string[]> => ({ ko: Object.keys(ko).sort(), en: Object.keys(en).sort() });

export type T = (key: string, vars?: Record<string, unknown>) => string;

export function makeT(locale: string, vars0: Record<string, unknown> = {}): T {
  const d = DICTS[locale] || ko;
  return (key, vars) => {
    const s = d[key] ?? ko[key] ?? key;
    const v = { ...vars0, ...vars };
    return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in v ? String(v[k]) : m));
  };
}
