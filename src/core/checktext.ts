/** '{n}개' 같은 자리에 값을 넣는다 */
export function fillText(s: string, vars: Record<string, unknown> = {}): string {
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** 점검 문구 하나 (없는 말이면 한국어, 없는 낱말이면 key) */
export function checkText(lang: string, key: string, vars?: Record<string, unknown>): string {
  const d = CHECK_TEXT[lang === 'en' ? 'en' : 'ko'];
  return fillText(d[key] ?? CHECK_TEXT.ko[key] ?? key, vars);
}
